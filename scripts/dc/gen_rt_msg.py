#!/usr/bin/env python3
"""Generate the `rt_warn` / `rt_error` specs from one template.

The two functions (`lib/number.c`) are the same code at a different base with
a different prefix message, so `scripts/dc/rt_msg.lean.in` is instantiated
once per function: the epilogue, the newline call, the `vfprintf` call and
the entry, over the shared `RtAt` state (`Dc/Mach/RtMsg.lean`).

Output (do not hand-edit): `Dc/Mach/RtMsgSites.lean`.

    python3 scripts/dc/gen_rt_msg.py [--check]
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
TEMPLATE = ROOT / "scripts/dc/rt_msg.lean.in"
OUT = ROOT / "Dc/Mach/RtMsgSites.lean"

# function, name prefix, spec name, entry PC, prefix message (RtMsg constant, address, length), text
FUNS = [
    ("rt_warn", "rtw", "rt_warn_spec", 0x80002c50, "rtWarnPre", 0x80007d50, 17, "Runtime warning"),
    ("rt_error", "rte", "rt_error_spec", 0x80002bd0, "rtErrPre", 0x80007d40, 15, "Runtime error"),
]

HEAD = """import Dc.Mach.RtMsg

/-!
# `rt_warn` and `rt_error` specs (generated by `scripts/dc/gen_rt_msg.py`; do not edit)
-/

namespace Dc.Mach

open Vsa.MemRepr Vsa.Sim VsaIris VsaIris.Inst VsaIris.Sym VsaIris.MallocFast
open LeanRV64DExecutable LeanRV64DExecutable.Functions Sail

"""


def render():
    tpl = TEMPLATE.read_text()
    parts = [HEAD]
    for fn, p, spec, e, pre, pa, pn, text in FUNS:
        subst = {
            "@FN@": fn, "@P@": p, "@SPEC@": spec, "@TEXT@": text, "@PRE@": pre,
            "@PREMSG@": f"{pa:#x} {pn}",
            "@ENTRY@": f"{e:#x}", "@VF@": f"{e + 0x48:#x}", "@NL@": f"{e + 0x5c:#x}",
            "@EPI@": f"{e + 0x6c:#x}", "@RA1@": str(e + 0x48),
            "@S0A@": str(e + 8 + 0x5000), "@A1A@": str(e + 0x1c + 0x5000), "@PREA@": str(pa),
        }
        s = tpl
        for k, v in subst.items():
            s = s.replace(k, v)
        assert "@" not in s.replace("@[", ""), fn
        parts.append(s.rstrip("\n") + "\n\n")
    parts.append("end Dc.Mach\n")
    return "".join(parts)


def main():
    text = render()
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            sys.exit(f"{OUT} is stale; rerun {__file__}")
        return
    OUT.write_text(text)


if __name__ == "__main__":
    main()
