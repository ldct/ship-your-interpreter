#!/usr/bin/env python3
"""Decode lemmas for the instruction words of dc-port/dc-riscv-htif.elf.

Words already in the WHILE decode table (`scripts/decode_index.tsv`) keep
their lemma; every other word gets one in `Dc/Mach/DecodeTable/Part<k>.lean`,
in the same namespace and template (`Vsa.Sim.DecodeTable.decode_<word>`, the
fast grounding template of `experiments/gen_decode_table.py`). The ASTs in the
statements come from evaluating the Sail decoder (`scripts/dc/DecodeDump.lean`);
the kernel checks every lemma.

Outputs: `Dc/Mach/DecodeTable/Part<k>.lean`, `Dc/Mach/DecodeTable.lean`,
`experiments/dc/decode_index.tsv` (word, module) for every word of the ELF.

    python3 scripts/dc/gen_dc_decode.py --vsa-olean DIR [--check]

`experiments/dc/disasm.txt` is `riscv-none-elf-objdump -d` of the ELF.
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PER_FILE = 100
TEMPLATE = '''theorem decode_{w}
    (σ : SequentialState RegisterType trivialChoiceSource)
    (_hmisa : σ.regs.get? Register.misa =
      some ((Vsa.Sim.initMisa) : RegisterType Register.misa))
    (hpriv : σ.regs.get? Register.cur_privilege =
      some (Privilege.Machine : RegisterType Register.cur_privilege))
    (hsec : σ.regs.get? Register.mseccfg =
      some ((0#64) : RegisterType Register.mseccfg)) :
    (ext_decode 0x{w}#32).run σ =
      .ok ({ast}) σ := by
  simp only [ext_decode, encdec_backwards, EStateM.run, bind, EStateM.bind,
    pure, EStateM.pure, PreSail.readReg, get, getThe, MonadStateOf.get, EStateM.get,
    currentlyEnabled, hartSupports, get_xLPE, Vsa.Sim.initMisa,
    _hmisa, hpriv, hsec]
  rfl
'''
HEADER = '''-- Generated by scripts/dc/gen_dc_decode.py; do not edit.
import LeanRiscv
import Vsa.Sim.InitValues
import Vsa.Sim.DecodeTable.DecodeCommon

/-! Decode lemmas for instruction words of `dc-port/dc-riscv-htif.elf` that the
WHILE table does not cover, part {k}. -/

open LeanRV64DExecutable LeanRV64DExecutable.Functions Sail ConcurrencyInterfaceV1 Vsa
open Register

set_option linter.unusedSimpArgs false

namespace Vsa.Sim.DecodeTable

'''


def elf_words():
    words = set()
    for line in open(ROOT / "experiments/dc/disasm.txt"):
        m = re.match(r"^\s+([0-9a-f]+):\t([0-9a-f]{8})\s", line)
        if m:
            words.add(m.group(2))
    return sorted(words)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--vsa-olean", required=True)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    known = {}
    for line in open(ROOT / "scripts/decode_index.tsv"):
        w, mod = line.split()
        known[w] = mod
    words = elf_words()
    new = [w for w in words if w not in known]

    dump = subprocess.run(
        ["lake", "env", "sh", "-c",
         f'LEAN_PATH="{args.vsa_olean}:$LEAN_PATH" lean --run scripts/dc/DecodeDump.lean'],
        cwd=ROOT, input="\n".join(new) + "\n", capture_output=True, text=True, check=True)
    asts = {}
    for line in dump.stdout.splitlines():
        if ";OK;" in line:
            w, _, ast = line.split(";", 2)
            asts[w] = " ".join(ast.split())
    missing = [w for w in new if w not in asts]
    if missing:
        print("words the decoder rejects:", " ".join(missing))
        return 1

    outdir = ROOT / "Dc/Mach/DecodeTable"
    files = {}
    index = dict(known)
    parts = [new[i:i + PER_FILE] for i in range(0, len(new), PER_FILE)]
    for k, part in enumerate(parts):
        mod = f"Dc.Mach.DecodeTable.Part{k:02d}"
        files[outdir / f"Part{k:02d}.lean"] = (
            HEADER.format(k=k) + "\n".join(TEMPLATE.format(w=w, ast=asts[w]) for w in part)
            + "\nend Vsa.Sim.DecodeTable\n")
        for w in part:
            index[w] = mod
    files[ROOT / "Dc/Mach/DecodeTable.lean"] = (
        "-- Generated by scripts/dc/gen_dc_decode.py; do not edit.\n"
        + "".join(f"import Dc.Mach.DecodeTable.Part{k:02d}\n" for k in range(len(parts))))
    files[ROOT / "experiments/dc/decode_index.tsv"] = "".join(
        f"{w}\t{index[w]}\n" for w in words)

    stale = [p for p, c in files.items() if not p.exists() or p.read_text() != c]
    if args.check:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}")
        return 1 if stale else 0
    outdir.mkdir(parents=True, exist_ok=True)
    for p in stale:
        p.write_text(files[p])
    print(f"{len(words)} words: {len(words) - len(new)} in the WHILE table, "
          f"{len(new)} new in {len(parts)} parts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
