#!/usr/bin/env python3
"""Generate the four regular struct-source dispatches of `_bc_rec_mul`'s
Karatsuba step.

Each inlined `new_sub_num` takes its struct off `_bc_Free_list` (the head in
one register, the link word stored back) or, with the chain empty, from
`malloc(40)`, going to `out_of_memory` when that returns `NULL`. Both routes
hand the view site a `ViewStruct` (`Dc/Mach/Bc/KaraViews.lean`), the struct's
payload in one register and the new chain head in another.

Output (do not hand-edit): `Dc/Mach/Bc/KaraPopSites.lean`.

    python3 scripts/dc/gen_kara_pop.py [--check]
"""
import pathlib
import sys

# (test PC, view-site PC, malloc stub PC, head reg, struct reg, link reg)
SITES = [
    (0x80004df8, 0x80004e08, 0x80005588, 14, 24, 19),
    (0x80004e30, 0x80004e3c, 0x80005604, 19, 19, 15),
    (0x8000538c, 0x8000539c, 0x800055d4, 14, 19, 15),
    (0x800053c0, 0x800053d0, 0x800055bc, 15, 27, 20),
]

OUT = pathlib.Path(__file__).resolve().parents[2] / "Dc/Mach/Bc/KaraPopSites.lean"

HEAD = """import Dc.Mach.Bc.KaraSplit

/-!
# `_bc_rec_mul`'s struct-source dispatches (generated)

Generated by `scripts/dc/gen_kara_pop.py`; do not hand-edit.
-/

namespace Dc.Mach

open Vsa.MemRepr Vsa.Sim VsaIris VsaIris.Inst VsaIris.Sym VsaIris.MallocFast
open LeanRV64DExecutable LeanRV64DExecutable.Functions Sail
open Dc.BcModel

set_option linter.unusedSimpArgs false
set_option maxRecDepth 8000
"""


def hx(n):
    return f"{n:08x}"


def gen():
    tmpl = (pathlib.Path(__file__).resolve().parent / "kara_pop.lean.in").read_text()
    out = [HEAD]
    for (t, e, ms, h, s, lk) in SITES:
        keep = sorted({1, 10, 12, 13, 14, 15, s, lk})
        txt = tmpl
        for k, val in [("@T@", hx(t)), ("@E@", hx(e)), ("@MS@", hx(ms)), ("@h@", str(h)),
                       ("@s@", str(s)), ("@t@", str(lk)),
                       ("@KEEP@", "[" + ", ".join(map(str, keep)) + "]")]:
            txt = txt.replace(k, val)
        out.append(txt)
    out.append("\nend Dc.Mach\n")
    return "".join(out)


def main():
    text = gen()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale; run {sys.argv[0]}")
            sys.exit(1)
        return
    OUT.write_text(text)


if __name__ == "__main__":
    main()
