#!/usr/bin/env python3
"""Generate the two-node stack checks of `dc_binop`, `dc_binop2`, `dc_cmpop`.

Each function opens with the same eight instructions after loading the stack
head into `a5`:

    beqz a5,EM; ld a4,24(a5); beqz a4,EM; lw a5,0(a5); li a3,1; bne a5,a3,NN;
    lw rT,0(a4); beq rT,a5,GO

`scripts/dc/stk_check.lean.in` is instantiated once per site over the
generic case split `DcAt.top2` (`Dc/Mach/DcStkCheck.lean`). A new site is one
`SITES` row.

Output (do not hand-edit): `Dc/Mach/DcStkCheckSites.lean`.

    python3 scripts/dc/gen_stk_check.py [--check]
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
TEMPLATE = ROOT / "scripts/dc/stk_check.lean.in"
OUT = ROOT / "Dc/Mach/DcStkCheckSites.lean"

REGS = {14: "a4", 17: "a7"}

# function, check PC (the first beqz), stack-empty PC, non-numeric PC, go PC, second-type register
SITES = [
    ("dc_binop", 0x800031D0, 0x8000320C, 0x800031F0, 0x80003228, 14),
    ("dc_binop2", 0x800032F0, 0x8000332C, 0x80003310, 0x80003348, 17),
    ("dc_cmpop", 0x8000346C, 0x800034BC, 0x8000348C, 0x800034DC, 14),
]

HEAD = """import Dc.Mach.DcStkCheck

/-!
# Two-node stack checks (generated by `scripts/dc/gen_stk_check.py`; do not edit)
-/

namespace Dc.Mach

open Vsa.MemRepr Vsa.Sim VsaIris VsaIris.Inst VsaIris.Sym VsaIris.MallocFast
open LeanRV64DExecutable LeanRV64DExecutable.Functions Sail

set_option linter.unusedSimpArgs false

local macro_rules | `(tactic| sx_side) => `(tactic| dc_side)

"""


def regs(base, rt):
    return "[" + ", ".join(str(r) for r in base + ([rt] if rt not in base else [])) + "]"


def render():
    tpl = TEMPLATE.read_text()
    parts = [HEAD]
    for fn, b, em, nn, go, rt in SITES:
        subst = {
            "@FN@": fn, "@BX@": f"{b:x}", "@B@": f"{b:#x}", "@EM@": f"{em:#x}",
            "@NN@": f"{nn:#x}", "@GO@": f"{go:#x}", "@RT@": str(rt), "@RTN@": REGS[rt],
            "@KNO@": regs([11, 12, 13, 14, 15], rt), "@KGO@": regs([13, 14, 15], rt),
        }
        s = tpl
        for k, v in subst.items():
            s = s.replace(k, v)
        assert "@" not in s, fn
        parts.append(s.rstrip("\n") + "\n\n")
    parts.append("end Dc.Mach\n")
    return "".join(parts)


def main():
    text = render()
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            sys.exit(f"{OUT} is stale; rerun {__file__}")
        return
    OUT.write_text(text)


if __name__ == "__main__":
    main()
