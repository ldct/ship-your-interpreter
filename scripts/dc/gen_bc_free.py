#!/usr/bin/env python3
"""Generate inlined `bc_free_num` sites on a register with an `auipc` free-list push.

Each site (`Dc/Mach/Bc/FreeSite.lean`) is described by its program points:

    P0  site start (the optional `beqz r, Nn` null test, else P)
    P   `lw a5,12(r)` ... `bnez a5, Nd`
    D   `ld a0,24(r)`, then the `n_ptr` branch (either polarity; registers
        written in between are in the clobber list `cl`)
    J   `jal free` (return to Uo)
    Uo  the push after `free`, ending at No
    Uv  the push for a view, ending at Nv

and gets `ffree_<P0>` (one `FreeK cl` continuation per route) plus, with a
null test, `fnull_<P0>`.

Output (do not hand-edit): `Dc/Mach/Bc/FreeSites.lean`.

    python3 scripts/dc/gen_bc_free.py [--check]
"""
import pathlib
