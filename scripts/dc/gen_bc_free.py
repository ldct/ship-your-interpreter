NULL = """/-- No number to free at `0x{P0}` (`x{r} = NULL`). -/
theorem fnull_{P0} {live : Nat → Prop} {S : Nat → Prop}
    {Q : (Nat → BitVec 64) → (Nat → BitVec 8) → Prop} (hlive : ∀ p ∈ dcText, live p.1)
    {M : Mem} {R : Nat → BitVec 64} (hS : HeapOwn S) (h0 : R {r} = 0#64)
    (hk : DW live S Q 0x{Nn}#64 R M) :
    DW live S Q 0x{P0}#64 R M := by
  have htx : tohostAddr = 0x8001ad00 := rfl
  bc_run hlive hS [h0] at 0x{Nn}
  all_goals first | exact hk | (intro hc; exact absurd rfl hc)

"""


def hx(v):
    return "%08x" % v


def site(name, p0, r, nn, p, d, j, uo, no, uv, nv, nd, extra, full):
    cl = "[" + ", ".join(str(z) for z in sorted(BASE_CL + extra)) + "]"
    sub = {"P0": p0, "P": p, "D": d, "J": j, "Uo": uo, "No": no, "Uv": uv, "Nv": nv,
           "Nd": nd}
    out = []
    for (u, n) in sorted({(uo, no), (uv, nv)}):
        s = PUSH
        for k, v in {"P0": p0, "U": u, "U4": u + 4, "N": n}.items():
            s = s.replace("{" + k + "}", hx(v))
        out.append(s.replace("{r}", str(r)).replace("{CL}", cl))
    s = TEMPLATE + (TEMPLATE_P.replace("{NULLSTEP}", NULLSTEP if nn is not None else "")
                    if full else "")
    if nn is not None:
        s += NULL
        sub["Nn"] = nn
    for k, v in sorted(sub.items(), key=lambda kv: -len(kv[0])):
        s = s.replace("{" + k + "}", hx(v))
    out.append(s.replace("{r}", str(r)).replace("{CL}", cl).replace("{name}", name))
    return "".join(out)


def render():
    return HEAD + "".join(site(*x) for x in SITES) + "end Dc.Mach\n"


def main():
    text = render()
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            sys.exit(f"{OUT} is stale; rerun {__file__}")
        return
    OUT.write_text(text)


if __name__ == "__main__":
    main()
