#!/usr/bin/env python3
"""Generate `evalstr`'s status dispatch lemmas.

After `dc_func` returns, `evalstr` jumps through the word table at
`0x80008134` (after a character with a lookahead; return `0x80001528`) or
`0x80008160` (after the last character; return `0x80001728`) on the status.
For each status `0..10` this emits `evm_<code>`/`evl_<code>` by
`ev_disp_tac`, the table word read from the ELF.

Output (do not hand-edit): `Dc/Mach/EvalRoute.lean`.

    python3 scripts/dc/gen_ev_disp.py [--check]
"""
import pathlib
import struct
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import gen_dcf_disp  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "Dc/Mach/EvalRoute.lean"

HEAD = 'import Dc.Mach.EvalExit\n\n/-!\n# `evalstr`\'s status dispatch (M10)\n\nAfter `dc_func` returns, `evalstr` jumps through one of two word tables on\nthe status (`s2 = 0x80008134` after a character with a lookahead, `s3 =\n0x80008160` after the last one). `ev_disp_tac` runs one status\'s dispatch\n(the bound test `bltu s4, a0`, the table word decided once, the `jr`);\n`evm_<code>`/`evl_<code>` are its instances (generated by\n`scripts/dc/gen_ev_disp.py`; do not edit).\n-/\n\nnamespace Dc.Mach\n\nopen Vsa.MemRepr Vsa.Sim VsaIris VsaIris.Inst VsaIris.Sym VsaIris.MallocFast VsaIris.Interp\nopen LeanRV64DExecutable LeanRV64DExecutable.Functions Sail\n\nset_option linter.unusedSimpArgs false\n\nlocal macro_rules | `(tactic| sx_side) => `(tactic| dc_side)\n\nset_option hygiene false in\n/-- One status\'s dispatch: the table word at `addr` is `val`, the target `tgt`. -/\nmacro "ev_disp_tac " stop:num addr:num val:num tgt:num : tactic =>\n  `(tactic| (\n    have htx : tohostAddr = 0x8001ad00 := rfl\n    bc_run hlive hlive [h10, cs.s2, cs.s3, cs.s4] at $stop\n    bc_run hlive hlive [h10, cs.s2, cs.s3, cs.s4] at $stop\n    dx_ro hlive\n    · gnorm; decide\n    · gnorm; decide +kernel\n    gnorm\n    simp only [BitVec.reduceShiftLeftShiftLeft, BitVec.reduceHShiftLeft, BitVec.reduceAdd,\n      BitVec.reduceToNat]\n    rw [show ldvf .lw dcROImg $addr = BitVec.ofNat 64 $val by decide +kernel]\n    bc_run hlive hlive [cs.s2, cs.s3] at $tgt\n    exact hk _ (by keeps_tac Keeps.refl _ _)))\n\n'

LEMMA = "/-- Status `{code}` after {what}: to `{tgt:#x}`. -/\ntheorem ev{tag}_{code} {{live S : Nat → Prop}} {{Q : String → (Nat → BitVec 64) → (Nat → BitVec 8) → Prop}}\n    (hlive : ∀ p ∈ dcText, live p.1) {{t : String}} {{R : Nat → BitVec 64}} {{M : Mem}}\n    (h10 : R 10 = BitVec.ofNat 64 {code}) (cs : EvConsts R)\n    (hk : ∀ R', Keeps [10, 15] R' R → DWO live S Q t {tgt:#x}#64 R' M) :\n    DWO live S Q t {pc:#x}#64 R M := by\n  ev_disp_tac {stop:#x} {addr} {val} {tgt:#x}\n\n"


def render():
    out = [HEAD]
    for base, tag, pc, stop, what in ((0x80008134, 'm', 0x80001528, 0x80001534, 'a character with a lookahead'),
                                      (0x80008160, 'l', 0x80001728, 0x80001734, 'the last character')):
        for code in range(11):
            addr = base + 4 * code
            off = struct.unpack('<i', gen_dcf_disp.read(addr, 4))[0]
            out.append(LEMMA.format(code=code, tag=tag, tgt=base + off, pc=pc, stop=stop, addr=addr,
                                    val=off % 2**64, what=what))
    out.append("end Dc.Mach\n")
    return "".join(out)


def main():
    text = render()
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            sys.exit(f"{OUT} is stale; rerun {__file__}")
        return
    OUT.write_text(text)


if __name__ == "__main__":
    main()
