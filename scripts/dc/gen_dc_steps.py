#!/usr/bin/env python3
"""Generate the dc binary's code image and its per-instruction step table.

The dc twin of `scripts/gen_interp_steps.py`, over `DW` (`Dc/Mach/Run.lean`):
`SWP` whose read-only list is the ELF's `.text` and `.rodata` (`dcText`).

Outputs (do not hand-edit):

* `Dc/Mach/Code.lean`: `dcCode` (every `.text` byte), `dcRO` (every `.rodata`
  byte), `dcText := dcCode ++ dcRO`, `dcROImg` (`.rodata` as a byte function).
* `Dc/Mach/Steps/Part<k>.lean`: per instruction `dc_at_<pc>` (four code bytes,
  the shape `chain_facts` consumes), `dc_code_<pc>` at an observed site (its
  code footprint lies in `dcText`), one `#derive_case`-shaped segment (two for
  a branch) and step lemmas over `DW`:
  - `st_<pc>`: ALU, store, branch, `j`, `ret`, `jr`, `jal`, `jalr` calls,
    and a load from OWNED bytes (value `ldv k Mt ea`);
  - `stR_<pc>`: a load from `.rodata` (value `ldvf k dcROImg ea`);
  - `stO_<pc>`: `sltu`/`sltiu` (`snez`/`seqz`), outside the reflected block
    model, as an observed ALU step (`swp_alu`);
  - `stL_<pc>`: `lb`, outside the reflected block model, as an observed load
    of one owned byte (`swp_aluM`, `Dc/Mach/LoadObs.lean`);
  - `jalx_<pc>`: the `JalExec` fact of a `jal` site.
* `Dc/Mach/Tohost.lean`: per `sd` to `tohost` (base from the `auipc` before
  it) the HTIF site `tohost_<pc>` (`TohostSite`, `VsaIris/Vsa/Console.lean`),
  its decided `Cert`, its code footprint in `dcText`, and `stP_<pc>`: the
  store of a putchar word as one printing step of a symbolic run
  (`swp_putc`).

Instructions without a step lemma (listed in the report): `ebreak`, and
`_start`'s two instructions that set `gp` (a read-only register of `DW`).

Inputs: `experiments/dc/disasm.txt` (`objdump -d` of the ELF),
`experiments/dc/decode_index.tsv` (`gen_dc_decode.py`), the ELF.

    python3 scripts/dc/gen_dc_steps.py [--check]
"""
import pathlib
import re
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'scripts'))
from rv_steps import M64, sx12, classify_word, src as _src  # noqa: E402

ELF_PATH = ROOT / 'dc-port/dc-riscv-htif.elf'
GPV = 0x8001b510  # `gp` (dc-port/link.ld), the read-only constant of `roR`
TOHOST = 0x8001ad00  # `tohost` (dc-port/link.ld)
PER_FILE = 120
HEADER = '-- Generated by scripts/dc/gen_dc_steps.py; do not edit.'
CHECK = '--check' in sys.argv


def src(r):
    return _src(r, GPV)


# ---------------------------------------------------------------- inputs
W, MN, FN = {}, {}, {}
fn = None
for line in open(ROOT / 'experiments/dc/disasm.txt'):
    m = re.match(r'^([0-9a-f]+) <(.*)>:$', line)
    if m:
        fn = m.group(2)
        continue
    m = re.match(r'^\s+([0-9a-f]+):\t([0-9a-f]{8})\s+\t(\S+)', line)
    if m:
        pc = int(m.group(1), 16)
        W[pc] = int(m.group(2), 16)
        MN[pc] = m.group(3)
        FN[pc] = fn
PCS = sorted(W)

DEC = {}
for line in open(ROOT / 'experiments/dc/decode_index.tsv'):
    w, mod = line.split()
    DEC[int(w, 16)] = mod

ELF = ELF_PATH.read_bytes()


def section(name):
    shoff = struct.unpack_from('<Q', ELF, 0x28)[0]
    shentsize, shnum, shstrndx = struct.unpack_from('<HHH', ELF, 0x3a)
    def hdr(i):
        return struct.unpack_from('<IIQQQQIIQQ', ELF, shoff + i * shentsize)
    stroff = hdr(shstrndx)[4]
    for i in range(shnum):
        nm, _, _, addr, off, size, _, _, _, _ = hdr(i)
        end = ELF.index(b'\0', stroff + nm)
        if ELF[stroff + nm:end].decode() == name:
            return addr, ELF[off:off + size]
    raise SystemExit(f'no section {name}')


RO_ADDR, RO_BYTES = section('.rodata')


def classify(pc):
    w = W[pc]
    if (w >> 7) & 31 == 3 and w & 0x7f in (0x13, 0x17, 0x37, 0x33, 0x1b, 0x3b, 0x03):
        return ('unsupported', None)  # writes `gp`, read-only in `DW` (only `_start` does)
    op, rd, f3, rs1, f7 = w & 0x7f, (w >> 7) & 31, (w >> 12) & 7, (w >> 15) & 31, w >> 25
    rs2 = (w >> 20) & 31
    if op == 0x03 and f3 == 0 and rd != 0:
        return ('lbs', dict(rd=rd, rs1=rs1, imm=(w >> 20) & 0xfff))
    if op == 0x33 and f3 == 3 and f7 == 0 and rd != 0:
        return ('obs', dict(kind='sltu', rd=rd, rs1=rs1, rs2=rs2))
    if op == 0x13 and f3 == 3 and rd != 0:
        return ('obs', dict(kind='sltiu', rd=rd, rs1=rs1, imm=(w >> 20) & 0xfff))
    if op == 0x67 and f3 == 0:
        imm = w >> 20
        if rd == 0 and rs1 == 1 and imm == 0:
            return ('ret', {})
        if rd == 0 and imm == 0:
            return ('jr', dict(rs1=rs1))
        if rd == 0:
            return ('jri', dict(rs1=rs1, imm=imm))
        if rd == 1 and rs1 != 0:
            return ('jalr', dict(rs1=rs1, imm=imm))
    return classify_word(pc, w, GPV)


# ---------------------------------------------------------------- the code image
code = []
for pc in PCS:
    for i in range(4):
        code.append((pc + i, (W[pc] >> (8 * i)) & 0xff))
ro = [(RO_ADDR + i, b) for i, b in enumerate(RO_BYTES)]
BYTE = dict(code)
CH = 16


def tree(items, name):
    """A balanced append tree of 16-byte chunks: definitions, the root node,
    and a membership proof builder."""
    chunks = [items[i:i + CH] for i in range(0, len(items), CH)]
    where = {a: j for j, c in enumerate(chunks) for (a, _) in c}
    defs = []

    def node(lo, hi):
        return f'{name}Chunk{lo}' if hi - lo == 1 else f'{name}Node{lo}_{hi}'

    def build(lo, hi):
        if hi - lo == 1:
            return
        mid = (lo + hi) // 2
        build(lo, mid)
        build(mid, hi)
        defs.append(f'def {node(lo, hi)} : List (Nat × BitVec 8) :=\n  {node(lo, mid)} ++ {node(mid, hi)}\n')

    for j, c in enumerate(chunks):
        defs.append(f'def {name}Chunk{j} : List (Nat × BitVec 8) :=\n  ['
                    + ', '.join(f'(0x{a:x}, 0x{b:02x}#8)' for a, b in c) + ']\n')
    build(0, len(chunks))
    byte = dict(items)

    def mem(a):
        j = where[a]
        pf = f'(by decide : ((0x{a:x} : Nat), (0x{byte[a]:02x}#8 : BitVec 8)) ∈ {name}Chunk{j})'
        path, lo, hi = [], 0, len(chunks)
        while hi - lo > 1:
            mid = (lo + hi) // 2
            if j < mid:
                path.append(('L', node(mid, hi)))
                hi = mid
            else:
                path.append(('R', node(lo, mid)))
                lo = mid
        for side, other in reversed(path):
            pf = (f'List.mem_append_left {other} ({pf})' if side == 'L'
                  else f'List.mem_append_right {other} ({pf})')
        return pf

    return defs, node(0, len(chunks)), mem


code_defs, CODE_ROOT, code_mem = tree(code, 'dcCode')
ro_defs, RO_ROOT, _ = tree(ro, 'dcRO')


def text_mem(a):
    """Proof term of `(a, BYTE[a]) ∈ dcText` for a code byte."""
    return f'List.mem_append_left dcRO ({code_mem(a)})'


OBS_SITES = [pc for pc in PCS if classify(pc)[0] in ('obs', 'lbs', 'jal', 'jalr')]


def at_lemmas(pc):
    """`dc_at_<pc>` (and `dc_code_<pc>` at an observed site) for one instruction."""
    bs = [BYTE[pc + i] for i in range(4)]
    C = [f'theorem dc_at_{pc:08x} {{m : Mem}} (h : TextLoaded dcText m) :',
         '    ' + ' ∧\n    '.join(f'm[(0x{pc + i:x} : Nat)]? = some (0x{bs[i]:02x} : BitVec 8)'
                                   for i in range(4)) + ' :=',
         '  ⟨' + ',\n   '.join(f'h _ ({text_mem(pc + i)})' for i in range(4)) + '⟩\n']
    if pc in OBS_SITES:
        cs = ', '.join(f'0x{b:02x}#8' for b in bs)
        C += [f'theorem dc_code_{pc:08x} : ∀ p ∈ codeFoot 0x{pc:x} [{cs}], (p.1, p.2.2) ∈ dcText := by',
              '  intro p hp',
              '  simp only [codeFoot, List.zipIdx, List.zipIdx_cons, List.zipIdx_nil, List.map_cons, List.map_nil,',
              '    List.mem_cons, List.not_mem_nil, or_false] at hp',
              '  rcases hp with rfl | rfl | rfl | rfl']
        C += [f'  · exact {text_mem(pc + i)}' for i in range(4)] + ['']
    return C


def gen_code():
    C = [HEADER, 'import VsaIris.Vsa.SymRun', '',
         '/-! The code image of `dc-port/dc-riscv-htif.elf`: every `.text` byte (`dcCode`)',
         'and every `.rodata` byte (`dcRO`), as balanced append trees of 16-byte chunks.',
         'The per-instruction byte lemmas `dc_at_<pc>` live beside the step lemmas. -/', '',
         'namespace Dc.Mach', '', 'open Vsa.MemRepr Vsa.Sim VsaIris.Sym', '']
    C += code_defs + ro_defs
    C.append('/-- The `.text` bytes: `(address, byte)`. -/')
    C.append(f'def dcCode : List (Nat × BitVec 8) := {CODE_ROOT}\n')
    C.append('/-- The `.rodata` bytes. -/')
    C.append(f'def dcRO : List (Nat × BitVec 8) := {RO_ROOT}\n')
    C.append('/-- The read-only bytes every run fetches or loads. -/')
    C.append('def dcText : List (Nat × BitVec 8) := dcCode ++ dcRO\n')
    C.append('/-- `.rodata` as a byte function (`0` elsewhere). -/')
    C.append('def dcROImg (a : Nat) : BitVec 8 := (dcRO.lookup a).getD 0\n')
    C.append('end Dc.Mach\n')
    return '\n'.join(C)


# ---------------------------------------------------------------- the step table


def ks_of(regs):
    return sorted({r for r in regs if r != 0})


def lst(xs):
    return '[' + ', '.join(str(x) for x in xs) + ']'


def hR(ks):
    if not ks:
        return '(fun _ h => nomatch h)'
    alts = ' | '.join(['rfl'] * len(ks))
    return ('(by intro x hx hg; simp only [List.mem_cons, List.not_mem_nil, or_false] at hx; '
            f'rcases hx with {alts} <;> first | rfl | exact absurd rfl hg)')


def hRo(ks, rd=None):
    if rd is None:
        return '(fun _ _ _ _ => rfl)'
    return f'(fun x _ _ hx => upd_other _ _ (fun e => hx (e ▸ (by decide : {rd} ∈ {lst(ks)}))))'


def hgp(ks):
    return '(fun _ => rfl)' if 3 in ks else '(fun h => absurd h (by decide))'


def hdr(name, pc):
    return (f"theorem {name}_{pc:08x} {{live : Nat → Prop}} {{S : Nat → Prop}}\n"
            f"    {{Q : (Nat → BitVec 64) → (Nat → BitVec 8) → Prop}} {{R : Nat → BitVec 64}} {{Mt : Mem}}\n"
            f"    (hlive : ∀ p ∈ dcText, live p.1)")


CF = 'chain_facts hm with "Dc.Mach.dc_at_"'


def step(seg, ks, lds, LD, Wr, cover, tail, hpc, R, Ro, hk, ind='  '):
    t = f'; {tail}' if tail else ''
    ld = 'hLDS' if LD != '[]' else '(fun a h => by cases h)'
    wr = 'hS' if Wr != '[]' else '(fun a h => by cases h)'
    return (f'{ind}swp_step {seg} {lst(ks)} {lds} {LD} {Wr} 0 rfl (by decide) (by decide) (by decide)\n'
            f'{ind}  {cover} hlive\n'
            f'{ind}  (fun m hm hLD => by unfold {seg} ChainFacts; {CF}{t})\n'
            f'{ind}  (by decide) (by decide) {hgp(ks)} (by decide) {ld}\n'
            f'{ind}  {wr} {hpc}\n'
            f'{ind}  {R}\n'
            f'{ind}  {Ro} rfl {hk}')


def dw(pc_expr, R='R', Mt='Mt'):
    return f'DW live S Q {pc_expr} {R} {Mt}'


def decode_proof(w, st):
    return (f'(Vsa.Sim.DecodeTable.decode_{w:08x} (afterPrelude {st})\n'
            f'        (by rw [get?_afterPrelude {st} _ (by decide)]; exact hG.misa)\n'
            f'        (by rw [get?_afterPrelude {st} _ (by decide)]; exact hG.cur_privilege)\n'
            f'        (by rw [get?_afterPrelude {st} _ (by decide)]; exact hG.mseccfg))')


def emit(pc):
    cls, d = classify(pc)
    w = W[pc]
    bs = [(w >> (8 * i)) & 0xff for i in range(4)]
    code_s = ', '.join(f'0x{b:02x}#8' for b in bs)
    nxt = f'0x{pc + 4:x}#64'
    segs, thm = [], []
    if cls == 'unsupported':
        return None, None
    single = f'def dx_{pc:08x} : List BBlock := [{{ body := [mkLine 0x{pc:x}#64 0x{w:08x}#32], term := none }}]'

    def tinstr(kind, rs1, rs2, i13, i21, i12=None):
        return (f'⟨0x{pc:x}#64, 0x{w:08x}#32, 0x{bs[0]:02x}#8, 0x{bs[1]:02x}#8, 0x{bs[2]:02x}#8, '
                f'0x{bs[3]:02x}#8, {kind}, {rs1}, {rs2}, 0x{i13 & 0x1fff:x}#13, 0x{i21 & 0x1fffff:x}#21, '
                + ('0#12⟩' if i12 is None else f'0x{i12:03x}#12⟩'))

    def tdef(name, kind, rs1, rs2, i13, i21, i12=None):
        return f'def {name} : List BBlock := [⟨[], some ({tinstr(kind, rs1, rs2, i13, i21, i12)} : TInstr)⟩]'

    NIL = '(fun a _ => trivial)'
    if cls == 'alu':
        segs.append(single)
        ks = ks_of(d['srcs'] + [d['rd']])
        thm.append(hdr('st', pc) + f"""
    (hk : {dw(nxt, f"(upd R {d['rd']} ({d['val']}))")}) :
    {dw(f'0x{pc:x}#64')} :=
""" + step(f'dx_{pc:08x}', ks, '[]', '[]', '[]', NIL, '', 'rfl', hR(ks), hRo(ks, d['rd']), 'hk'))
    elif cls == 'load':
        segs.append(single)
        ea = f"({src(d['rs1'])} + {sx12(d['imm'])}).toNat"
        wd = d['width']
        ks = ks_of([d['rs1'], d['rd']])
        suf = str(wd)
        thm.append(hdr('st', pc) + f"""
    (hea : LdOK {ea} {wd})
    (hLDS : ∀ b ∈ accAddrs {ea} {wd}, S b)
    (hk : {dw(nxt, f"(upd R {d['rd']} (ldv .{d['kind']} Mt {ea}))")}) :
    {dw(f'0x{pc:x}#64')} :=
""" + step(f'dx_{pc:08x}', ks, f'[bytesAt (imgM Mt) {ea} {wd}]', f'(accAddrs {ea} {wd})', '[]', NIL,
           f'exact ⟨hea, lpins{suf}_img hLD⟩', 'rfl', hR(ks), hRo(ks, d['rd']), 'hk'))
        thm.append(hdr('stR', pc) + f"""
    (hea : LdOK {ea} {wd})
    (hLDT : ∀ b ∈ accAddrs {ea} {wd}, (b, dcROImg b) ∈ dcRO)
    (hk : {dw(nxt, f"(upd R {d['rd']} (ldvf .{d['kind']} dcROImg {ea}))")}) :
    {dw(f'0x{pc:x}#64')} :=
""" + step(f'dx_{pc:08x}', ks, f'[bytesAt dcROImg {ea} {wd}]', '[]', '[]', NIL,
           f'exact ⟨hea, lpins{suf}_fn (fun b hb => by rw [hm _ (List.mem_append_right _ (hLDT b hb))]; rfl)⟩',
           'rfl', hR(ks), hRo(ks, d['rd']), 'hk'))
    elif cls == 'store':
        segs.append(single)
        ea = f"({src(d['rs1'])} + {sx12(d['imm'])}).toNat"
        wd = d['width']
        ks = ks_of([d['rs1'], d['rs2']])
        ok = f'StOKb {ea}' if d['kind'] == 'sb' else f'StOK {ea} {wd}'
        thm.append(hdr('st', pc) + f"""
    (hea : {ok})
    (hS : ∀ b ∈ accAddrs {ea} {wd}, S b)
    (hk : {dw(nxt, 'R', f"(writeLog Mt [({ea}, {wd}, {src(d['rs2'])})])")}) :
    {dw(f'0x{pc:x}#64')} :=
""" + step(f'dx_{pc:08x}', ks, '[]', '[]', f'(accAddrs {ea} {wd})', '(fun a ha => outL_single _ ha)',
           'exact hea', 'rfl', hR(ks), hRo(ks), 'hk'))
    elif cls == 'br':
        A, B = src(d['rs1']), src(d['rs2'])
        cond = {'BEQ': f'{A} = {B}', 'BNE': f'{A} ≠ {B}', 'BLT': f'{A}.toInt < {B}.toInt',
                'BGE': f'{B}.toInt ≤ {A}.toInt', 'BLTU': f'{A}.toNat < {B}.toNat',
                'BGEU': f'{B}.toNat ≤ {A}.toNat'}[d['op']]
        gl = {'BEQ': 'guard_beq', 'BNE': 'guard_bne', 'BLT': 'guard_blt', 'BGE': 'guard_bge',
              'BLTU': 'guard_bltu', 'BGEU': 'guard_bgeu'}[d['op']]
        ks = ks_of([d['rs1'], d['rs2']])
        segs.append(tdef(f'dxT_{pc:08x}', f'.br bop.{d["op"]} true', d['rs1'], d['rs2'], d['imm'], 0))
        segs.append(tdef(f'dxF_{pc:08x}', f'.br bop.{d["op"]} false', d['rs1'], d['rs2'], d['imm'], 0))
        tgt = f'0x{d["tgt"]:x}#64'
        thm.append(hdr('st', pc) + f"""
    (hT : {cond} → {dw(tgt)}) (hF : ¬ ({cond}) → {dw(nxt)}) :
    {dw(f'0x{pc:x}#64')} := by
  by_cases hc : {cond}
  · exact
""" + step(f'dxT_{pc:08x}', ks, '[]', '[]', '[]', NIL, f'exact ({gl} _ _).2 hc', 'rfl',
           hR(ks), hRo(ks), '(hT hc)', '    ') + """
  · exact
""" + step(f'dxF_{pc:08x}', ks, '[]', '[]', '[]', NIL, f'exact (guard_false ({gl} _ _)).2 hc',
           'rfl', hR(ks), hRo(ks), '(hF hc)', '    '))
    elif cls == 'j':
        segs.append(tdef(f'dx_{pc:08x}', '.j', 0, 0, 0, d['imm']))
        thm.append(hdr('st', pc) + f"""
    (hk : {dw(f"0x{d['tgt']:x}#64")}) :
    {dw(f'0x{pc:x}#64')} :=
""" + step(f'dx_{pc:08x}', [], '[]', '[]', '[]', NIL, '', 'rfl', '(fun _ h => nomatch h)', hRo([]), 'hk'))
    elif cls in ('ret', 'jr'):
        r = 1 if cls == 'ret' else d['rs1']
        segs.append(tdef(f'dx_{pc:08x}', '.jr', r, 0, 0, 0))
        thm.append(hdr('st', pc) + f"""
    (hal : (R {r}).toNat % 4 = 0) (hk : {dw(f'(R {r})')}) :
    {dw(f'0x{pc:x}#64')} :=
""" + step(f'dx_{pc:08x}', [r], '[]', '[]', '[]', NIL,
           f'show (Sail.BitVec.update (R {r} + sign_extend (m := 64) (0x000#12)) 0 0#1).toNat % 4 = 0; '
           'rw [ret_tgt _ hal]; exact hal', '(ret_tgt _ hal)', hR([r]), hRo([r]), 'hk'))
    elif cls == 'jri':
        r, imm = d['rs1'], d['imm']
        tgt = f'(Sail.BitVec.update (R {r} + sign_extend (m := 64) (0x{imm:03x}#12)) 0 0#1)'
        segs.append(tdef(f'dx_{pc:08x}', '.jr', r, 0, 0, 0, imm))
        thm.append(hdr('st', pc) + f"""
    (hal : {tgt}.toNat % 4 = 0) (hk : {dw(tgt)}) :
    {dw(f'0x{pc:x}#64')} :=
""" + step(f'dx_{pc:08x}', [r], '[]', '[]', '[]', NIL, 'exact hal', 'rfl', hR([r]), hRo([r]), 'hk'))
    elif cls == 'obs':
        rd, rs1 = d['rd'], d['rs1']
        A = src(rs1)
        if d['kind'] == 'sltu':
            rs2 = d['rs2']
            B = src(rs2)
            val = f'zero_extend (m := 64) (bool_to_bit (zopz0zI_u {A} {B}))'
            srcs = [rs1, rs2]
            ast = (f'instruction.RTYPE (regidx.Regidx 0x{rs2:02x}#5, regidx.Regidx 0x{rs1:02x}#5, '
                   f'regidx.Regidx 0x{rd:02x}#5, rop.SLTU)')
        else:
            imm = d['imm']
            val = f'zero_extend (m := 64) (bool_to_bit (zopz0zI_u {A} (sign_extend (m := 64) (0x{imm:03x}#12))))'
            srcs = [rs1]
            ast = (f'instruction.ITYPE (0x{imm:03x}#12, regidx.Regidx 0x{rs1:02x}#5, '
                   f'regidx.Regidx 0x{rd:02x}#5, iop.SLTIU)')
        ks = ks_of(srcs)
        npc = f'(afterNextPC (afterPrelude c.σ) (0x{pc:x}#64))'

        def rx(r):
            if r == 0:
                return 'rX_bits_zero _'
            return (f'rX_bits_x{r} _ (R {r}) (by rw [get?_afterNextPC c.σ (0x{pc:x}#64) _ (by decide) (by decide)]; '
                    f'exact hRR ({r}, Iris.DFrac.own 1, R {r}) (by simp))')
        post = f'(sigma3_alu c.σ (0x{pc:x}#64) Register.x{rd} ({val}))'
        if d['kind'] == 'sltu':
            ex = (f'execute_rtype_sltu_char (regidx.Regidx 0x{rs2:02x}#5) (regidx.Regidx 0x{rs1:02x}#5) '
                  f'(regidx.Regidx 0x{rd:02x}#5) {A} {B} {npc} {post}\n'
                  f'        ({rx(rs1)})\n        ({rx(rs2)})\n'
                  f'        (wX_bits_x{rd} _ ({val}))')
        else:
            ex = (f'execute_itype_sltiu_char (0x{d["imm"]:03x}#12) (regidx.Regidx 0x{rs1:02x}#5) '
                  f'(regidx.Regidx 0x{rd:02x}#5) {A} {npc} {post}\n'
                  f'        ({rx(rs1)})\n'
                  f'        (wX_bits_x{rd} _ ({val}))')
