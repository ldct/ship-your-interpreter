#!/usr/bin/env python3
"""Generate `_bc_rec_mul`'s four inlined leading-zero trims.

Each trim at `E` works on the object whose struct pointer is in one register
(`s8`, `s3`, `s11`, `s4`): `ld` of `n_value`, the first digit, `bnez` to the
exit; else `n_len`, `blez`-style `bge` at the loop head `E + 0x14`, then the
body (advance `n_value`, lower `n_len`, load the next digit, `beqz` back).
Each copy gets

- `ktrimLoop_<H>`: the loop, by induction on the digits left;
- `ktrim_<E>`: the whole trim, handing on `NumRep.drop j` with
  `lzCount (len - 1) ds = j`.

`bc_multiply`'s inlined trim has the same loop (head `H`, struct register) but
its own preamble and scans the digits after it from `a5`; it gets
`ktrimLoop_<H>` only (`LOOPS`), whose exit also gives `a5 = n_value`.

Output (do not hand-edit): `Dc/Mach/Bc/KaraTrimSites.lean`.

    python3 scripts/dc/gen_kara_trim.py [--check]
"""
import pathlib
import sys

# (entry E, struct register)
SITES = [
    (0x80004eb0, 24),
    (0x80004ee0, 19),
    (0x80004f10, 27),
    (0x80004f40, 20),
]

# (loop head H, struct register): the loop alone
LOOPS = [
    (0x8000580c, 8),
]

OUT = pathlib.Path(__file__).resolve().parents[2] / "Dc/Mach/Bc/KaraTrimSites.lean"

HEAD = """import Dc.Mach.Bc.KaraTrim

/-!
# `_bc_rec_mul`'s leading-zero trims (generated)

Generated by `scripts/dc/gen_kara_trim.py`; do not hand-edit.
-/

namespace Dc.Mach

open Vsa.MemRepr Vsa.Sim VsaIris VsaIris.Inst VsaIris.Sym VsaIris.MallocFast
open LeanRV64DExecutable LeanRV64DExecutable.Functions Sail
open Dc.BcModel

set_option linter.unusedSimpArgs false
set_option maxRecDepth 8000
"""


def hx(n):
    return f"{n:08x}"


def gen():
    tmpl = (pathlib.Path(__file__).resolve().parent / "kara_trim.lean.in").read_text()
    loop = tmpl[:tmpl.index("/-- **The leading-zero trim at")]
    out = [HEAD]
    for (e, r) in SITES:
        t = tmpl
        for k, val in [("@E@", hx(e)), ("@H@", hx(e + 0x14)), ("@B@", hx(e + 0x28)),
                       ("@X@", hx(e + 0x30)), ("@r@", str(r)), ("@HN15@", ""), ("@P15@", ""),
                       ("@P15S@", "")]:
            t = t.replace(k, val)
        out.append(t)
    for (h, r) in LOOPS:
        t = loop
        for k, val in [("@H@", hx(h)), ("@B@", hx(h + 0x14)), ("@X@", hx(h + 0x1c)), ("@r@", str(r)),
                       ("@HN15@", "\n      R' 15 = BitVec.ofNat 64 (x.rep.val + j) →"),
                       ("@P15@", " (by bsimp [h15])"),
                       ("@P15S@", " (by bsimp [h15]; simp only [Nat.add_assoc])")]:
            t = t.replace(k, val)
        out.append("\n" + t.rstrip("\n") + "\n")
    out.append("\nend Dc.Mach\n")
    return "".join(out)


def main():
    text = gen()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale; run {sys.argv[0]}")
            sys.exit(1)
        return
    OUT.write_text(text)


if __name__ == "__main__":
    main()
