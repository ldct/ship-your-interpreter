#!/usr/bin/env python3
"""Generate inlined `bc_is_zero` digit scans of the `bc_divmod` layout.

Each scan (`B: beqz c, Z`; `L: lbu t, 0(p)`; `addiw c, c, -1`; `addi p, p, 1`;
`beqz t, B`; a nonzero digit falls through to `L + 16`) gets `zscan_<L>`: by
induction on the digits left, all `n` digits zero reach `Z`, a nonzero digit
reaches `L + 16`.

Output (do not hand-edit): `Dc/Mach/Bc/ZeroScanSites.lean`.

    python3 scripts/dc/gen_zero_scan.py [--check]
"""
import pathlib
import sys

# (lbu pc L, count reg c, pointer reg p, byte reg t, all-zero target Z, function)
SITES = [
    (0x80006220, 15, 11, 10, 0x8000646c, "`bc_raisemod`: `mod`"),
    (0x800062e8, 15, 16, 14, 0x800063b4, "`bc_raisemod`: `exponent`"),
    (0x80006338, 15, 14, 13, 0x80006378, "`bc_raisemod`: `parity`"),
]

OUT = pathlib.Path(__file__).resolve().parents[2] / "Dc/Mach/Bc/ZeroScanSites.lean"

HEAD = """import Dc.Mach.Bc.DivModEntry

/-!
# Inlined `bc_is_zero` digit scans (generated)

Generated by `scripts/dc/gen_zero_scan.py`; do not hand-edit.
-/

namespace Dc.Mach

open Vsa.MemRepr Vsa.Sim VsaIris VsaIris.Inst VsaIris.Sym VsaIris.MallocFast
open LeanRV64DExecutable LeanRV64DExecutable.Functions Sail
open Dc.BcModel

set_option linter.unusedSimpArgs false
set_option maxRecDepth 8000

"""

SCAN = """/-- **The zero test of @WHAT@** at `0x@L@` (inlined): digits `0 … i - 1`
zero, `x@c@ = n - i`, `x@p@` at digit `i`; the first nonzero digit ends it at
`0x@NZ@`, all `n` zero at `0x@Z@`. -/
theorem zscan_@L@ {live : Nat → Prop} {S : Nat → Prop}
    {Q : (Nat → BitVec 64) → (Nat → BitVec 8) → Prop} (hlive : ∀ p ∈ dcText, live p.1)
    {M : Mem} {Rb : Nat → BitVec 64} (hS : HeapOwn S) {ds : List Nat} (hd : IsDigits ds)
    {v n : Nat} (hb : ∀ i, i < n → imgM M (v + i) = BitVec.ofNat 8 (ds.getD i 0)) (hn : n < 2 ^ 30)
    (hlo : 2147603920 ≤ v) (hhi : v + n ≤ 2273312768)
    (hfound : ∀ R', (∃ i0, i0 < n ∧ ds.getD i0 0 ≠ 0) → Keeps @KS@ R' Rb →
      DW live S Q 0x@NZ@#64 R' M)
    (hnone : ∀ R', (∀ j, j < n → ds.getD j 0 = 0) → Keeps @KS@ R' Rb →
      DW live S Q 0x@Z@#64 R' M) :
    ∀ k i R, i + 1 + k = n → (∀ j, j < i → ds.getD j 0 = 0) → Keeps @KS@ R Rb →
      R @c@ = BitVec.ofNat 64 (n - i) → R @p@ = BitVec.ofNat 64 (v + i) →
      DW live S Q 0x@L@#64 R M := by
  have htx : tohostAddr = 0x8001ad00 := rfl
  refine count_rec fun k i R ih hi hz kk hc hp => ?_
  have hl := lbu_digit (hd.getD i) (hb i (by omega))
  have hdl := hd.getD i
  have e1 : BitVec.ofNat 64 (v + i) + 1#64 = BitVec.ofNat 64 (v + (i + 1)) := by
    rw [show (1#64) = BitVec.ofNat 64 1 from rfl, ofNat_add_ofNat]; congr 1
  have e2 := subw_ofNat_le (a := n - i) (b := 1) (by omega) (by omega)
  have hq := ofNat_eq_zero_iff (show ds.getD i 0 < 2 ^ 64 by omega)
  bc_run hlive hS [hc, hp, hl, e1, e2] at 0x@NZ@ 0x@B@
  all_goals first | exact acc_heap hS (by omega) (by omega) | skip
  · intro h0
    replace h0 : ds.getD i 0 = 0 := hq.mp h0
    have hz' : ∀ j, j < i + 1 → ds.getD j 0 = 0 := fun j hj => by
      rcases Nat.lt_or_ge j i with h | h
      · exact hz j h
      · rw [show j = i by omega]; exact h0
    have e3 := ofNat_eq_zero_iff (show n - i - 1 < 2 ^ 64 by omega)
    bc_run hlive hS [e3] at 0x@Z@ 0x@L@
    · intro h1
      exact hnone _ (fun j hj => hz' j (by omega)) (by keeps_tac kk)
    · intro h1
      rcases k with _ | k
      · omega
      exact ih k rfl _ (by omega) hz' (by keeps_tac kk) (by bsimp []; exact congrArg _ (by omega))
        (by bsimp [])
  · intro h0
    replace h0 : ds.getD i 0 ≠ 0 := fun e => h0 (hq.mpr e)
    exact hfound _ ⟨i, by omega, h0⟩ (by keeps_tac kk)

"""


def hx(n):
    return f"{n:08x}"


def gen():
    out = [HEAD]
    for (L, c, p, t, Z, what) in SITES:
        KS = "[" + ", ".join(map(str, sorted({c, p, t}))) + "]"
        s = SCAN
        for k, v in [("@L@", hx(L)), ("@B@", hx(L - 4)), ("@NZ@", hx(L + 16)), ("@Z@", hx(Z)),
                     ("@KS@", KS), ("@c@", str(c)), ("@p@", str(p)), ("@WHAT@", what)]:
            s = s.replace(k, v)
        out.append(s)
    out.append("end Dc.Mach\n")
    return "".join(out)


def main():
    text = gen()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale; run {sys.argv[0]}")
            sys.exit(1)
        return
    OUT.write_text(text)


if __name__ == "__main__":
    main()
