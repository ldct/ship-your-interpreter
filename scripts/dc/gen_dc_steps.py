def gen_steps():
    unsupported, parts = [], []
    cur = ([], [], set(), [])
    for pc in PCS:
        segs, thms = emit(pc) if W[pc] in DEC else (None, None)
        if segs is None:
            unsupported.append(pc)
            continue
        cur[0].extend(segs)
        cur[1].extend(at_lemmas(pc) + thms)
        cur[2].add(DEC[W[pc]])
        if classify(pc)[0] == 'lbs':
            cur[2].add('Dc.Mach.LoadObs')
        cur[3].append(pc)
        if len(cur[3]) >= PER_FILE:
            parts.append(cur)
            cur = ([], [], set(), [])
    if cur[3]:
        parts.append(cur)
    files = {}
    for k, (segs, thms, mods, pcs) in enumerate(parts):
        L = [HEADER, 'import Dc.Mach.Run'] + [f'import {m}' for m in sorted(mods)] + [
            '', f'/-! The dc step table, `0x{pcs[0]:x}` to `0x{pcs[-1]:x}` (see `scripts/dc/gen_dc_steps.py`). -/',
            '', 'open LeanRV64DExecutable LeanRV64DExecutable.Functions Sail', '',
            'set_option linter.unusedSimpArgs false', '',
            'namespace Dc.Mach', '', 'open VsaIris Vsa.Sim Vsa.MemRepr VsaIris.Sym VsaIris.Inst VsaIris.MallocFast', ''] + \
            segs + [''] + [t + '\n' for t in thms] + ['end Dc.Mach', '']
        files[f'Dc/Mach/Steps/Part{k:02d}.lean'] = '\n'.join(L)
    files['Dc/Mach/Steps.lean'] = '\n'.join(
        [HEADER] + [f'import Dc.Mach.Steps.Part{k:02d}' for k in range(len(parts))] + [''])
    return files, unsupported


def main():
    files = {'Dc/Mach/Code.lean': gen_code(), 'Dc/Mach/Tohost.lean': gen_tohost()}
    steps, unsupported = gen_steps()
    files.update(steps)
    stale = [p for p, c in files.items() if not (ROOT / p).exists() or (ROOT / p).read_text() != c]
    if CHECK:
        for p in stale:
            print(f'stale: {p}')
        return 1 if stale else 0
    (ROOT / 'Dc/Mach/Steps').mkdir(parents=True, exist_ok=True)
    for old in (ROOT / 'Dc/Mach/Steps').glob('Part*.lean'):
        if str(old.relative_to(ROOT)) not in files:
            old.unlink()
    for p in stale:
        (ROOT / p).write_text(files[p])
    print(f'{len(PCS)} instructions, {len(code)} code bytes, {len(ro)} rodata bytes, '
          f'{len(files) - 3} step files, {len(tohost_sites())} tohost stores')
    print('no step lemma:', ', '.join(f'0x{pc:x} {MN[pc]} ({FN[pc]})' for pc in unsupported))
    return 0


