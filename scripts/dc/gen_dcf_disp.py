#!/usr/bin/env python3
"""Generate `dc_func`'s per-character dispatch lemmas.

`dc_func` (`0x80000b9c`) jumps through the word table at `0x80007f5c` on
`c - 9`. For each `c` in `9..126` this emits `dcf_disp_<c>`: from the entry
with `a0 = c` to the arm the table names, by `dcf_disp_tac`
(`Dc/Mach/DcFuncBase.lean`) with the table word read from the ELF.

Output (do not hand-edit): `Dc/Mach/DcFuncDisp.lean`.

    python3 scripts/dc/gen_dcf_disp.py [--check]
"""
import pathlib
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
ELF = (ROOT / "dc-port/dc-riscv-htif.elf").read_bytes()
OUT = ROOT / "Dc/Mach/DcFuncDisp.lean"
TABLE = 0x80007F5C


def segments():
    phoff = struct.unpack_from("<Q", ELF, 0x20)[0]
    phentsize, phnum = struct.unpack_from("<HH", ELF, 0x36)
    segs = []
    for i in range(phnum):
        p_type, _, p_offset, p_vaddr, _, p_filesz, _, _ = struct.unpack_from("<IIQQQQQQ", ELF, phoff + i * phentsize)
        if p_type == 1:
            segs.append((p_vaddr, p_offset, p_filesz))
    return segs


SEGS = segments()


def read(a, n):
    for v, o, f in SEGS:
        if v <= a and a + n <= v + f:
            return ELF[o + a - v:o + a - v + n]
    raise KeyError(hex(a))


def entry(c):
    addr = TABLE + 4 * (c - 9)
    off = struct.unpack("<i", read(addr, 4))[0]
    return addr, off % 2**64, TABLE + off


HEAD = """import Dc.Mach.DcFuncBase

/-!
# `dc_func`'s dispatch per character (generated by `scripts/dc/gen_dcf_disp.py`; do not edit)

`dcf_disp_<c>`: from `dc_func`'s entry with `a0 = c` to the arm of `c`, the
frame open and `ra` spilled at `sp - 192 + 184`, `a3 = c`.
-/

namespace Dc.Mach

open Vsa.MemRepr Vsa.Sim VsaIris VsaIris.Inst VsaIris.Sym VsaIris.MallocFast VsaIris.Interp
open LeanRV64DExecutable LeanRV64DExecutable.Functions Sail

set_option linter.unusedSimpArgs false

"""

LEMMA = """theorem dcf_disp_{c} {{live S : Nat → Prop}} {{Q : String → (Nat → BitVec 64) → (Nat → BitVec 8) → Prop}}
    {{t : String}} (hlive : ∀ p ∈ dcText, live p.1) (hS : HeapOwn S) {{M : Mem}} {{sp : Nat}}
    (hsf : StackFrame S sp 192) (hab : heapEnd + 192 ≤ sp)
    (R : Nat → BitVec 64) (h2 : R 2 = BitVec.ofNat 64 sp) (h10 : R 10 = {c}#64)
    (hk : ∀ R', Keeps [2, 13, 14, 15] R' R → R' 2 = BitVec.ofNat 64 (sp - 192) → R' 13 = R 10 →
      DWO live S Q t {tgt:#x}#64 R' (writeLog M [(sp - 192 + 184, 8, R 1)])) :
    DWO live S Q t 0x80000b9c#64 R M := by
  dcf_disp_tac {addr} {val} {tgt:#x}

"""


def render():
    parts = [HEAD]
    for c in range(9, 127):
        addr, val, tgt = entry(c)
        parts.append(LEMMA.format(c=c, addr=addr, val=val, tgt=tgt))
    parts.append("end Dc.Mach\n")
    return "".join(parts)


def main():
    text = render()
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            sys.exit(f"{OUT} is stale; rerun {__file__}")
        return
    OUT.write_text(text)


if __name__ == "__main__":
    main()
