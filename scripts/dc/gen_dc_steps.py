def tohost_sites():
    """`sd rs2, imm(rs1)` to `tohost` with `rs1` set by the `auipc` before it."""
    out = []
    for pc in PCS:
        w = W[pc]
        if w & 0x7f != 0x23 or (w >> 12) & 7 != 3 or pc - 4 not in W:
            continue
        rs1, rs2 = (w >> 15) & 31, (w >> 20) & 31
        imm = ((w >> 25) << 5) | ((w >> 7) & 31)
        pw = W[pc - 4]
        if pw & 0x7f != 0x17 or (pw >> 7) & 31 != rs1:
            continue
        base = (pc - 4 + ((pw & 0xfffff000) - (1 << 32 if pw & 0x80000000 else 0))) & M64
        if (base + (imm - 4096 if imm & 0x800 else imm)) & M64 != TOHOST:
            continue
        out.append(dict(pc=pc, w=w, rs1=rs1, rs2=rs2, imm=imm, base=base))
    return out


