#!/usr/bin/env python3
"""Generate `_bc_rec_mul`'s inlined `bc_is_zero` tests.

Each test at `E` (`beq obj, zero` to `Z`, then for an object other than
`_zero_`: `lw`/`lw`/`addw` the digit count, `blez`, `ld` of `n_value`, `j`
into the scan at `L`; the scan `lbu t, 0(p)`, `beqz t` back to `B = L - 12`:
`addiw c, c, -1`, `addi p, p, 1`, `beqz c` to `Z`) gets

- `kscan_<L>`: the scan, by induction on the digits left;
- `kzero_<E>`: the test of a handle (`Hd`): `_zero_` itself, or a number all
  of whose digits are zero, reaches `Z`; any other number reaches `L + 8`.

A test preceded by `li a5, 0` and followed by `bnez a5, Z` (the second of a
pair) starts at the `li`.

Output (do not hand-edit): `Dc/Mach/Bc/KaraScanSites.lean`.

    python3 scripts/dc/gen_kara_scan.py [--check]
"""
import pathlib
import sys

# (entry E, second of a pair, obj reg, zero reg, count reg c, pointer reg p,
#  byte reg t, length reg (first lw), lbu pc L, zero target Z)
SITES = [
    (0x80004f70, False, 24, 17, 15, 14, 13, 14, 0x80004f98, 0x800054bc),
    (0x80004fa0, True, 27, 17, 26, 15, 14, 15, 0x80004fd0, 0x800054bc),
    (0x80005050, False, 21, 12, 15, 14, 13, 14, 0x80005078, 0x800054a8),
    (0x80005080, True, 23, 12, 15, 14, 13, 14, 0x800050b0, 0x800054a8),
    (0x800050d4, False, 19, 12, 15, 14, 13, 11, 0x800050fc, 0x80005440),
    (0x80005104, True, 20, 12, 15, 14, 10, 13, 0x80005134, 0x80005440),
]

OUT = pathlib.Path(__file__).resolve().parents[2] / "Dc/Mach/Bc/KaraScanSites.lean"

HEAD = """import Dc.Mach.Bc.KaraScan

/-!
# `_bc_rec_mul`'s inlined `bc_is_zero` tests (generated)

Generated by `scripts/dc/gen_kara_scan.py`; do not hand-edit.
-/

namespace Dc.Mach

open Vsa.MemRepr Vsa.Sim VsaIris VsaIris.Inst VsaIris.Sym VsaIris.MallocFast
open LeanRV64DExecutable LeanRV64DExecutable.Functions Sail

set_option linter.unusedSimpArgs false

"""

LOOP = """/-- The digit scan at `0x@L@`: the first `i` digits zero, `k + 1` left. -/
theorem kscan_@L@ {live : Nat → Prop} {S : Nat → Prop}
    {Q : (Nat → BitVec 64) → (Nat → BitVec 8) → Prop} (hlive : ∀ p ∈ dcText, live p.1)
    {M : Mem} {o : NumRep} {Rb : Nat → BitVec 64} (hS : HeapOwn S) (hn : NumAt M o)
    (hz : ∀ R', Keeps @KS@ R' Rb → (∀ j, j < o.len + o.scale → o.ds.getD j 0 = 0) →
      DW live S Q 0x@Z@#64 R' M)
    (hnz : ∀ R', Keeps @KS@ R' Rb → DW live S Q 0x@NZ@#64 R' M) :
    ∀ k i (R : Nat → BitVec 64), o.len + o.scale = i + k + 1 → (∀ j, j < i → o.ds.getD j 0 = 0) →
      Keeps @KS@ R Rb → R @c@ = BitVec.ofNat 64 (k + 1) → R @p@ = BitVec.ofNat 64 (o.val + i) →
      DW live S Q 0x@L@#64 R M := by
  num_facts hn
  intro k
  induction k with
  | zero =>
    intro i R hi hz0 kk hc hp
    have hl := hn.lbu (i := i) (by omega)
    have hd := hn.getD_lt i
    bc_run hlive hS [hc, hp, hl] at 0x@B@ 0x@NZ@
    all_goals first | exact acc_heap hS (by omega) (by omega) | skip
    · intro h0
      bsimp [ofNat_eq_zero_iff (show o.ds.getD i 0 < 2 ^ 64 by omega)] at h0
      bc_run hlive hS [hc, hp] at 0x@Z@ 0x@L@
      exact hz _ (by keeps_tac kk) fun j hj => by
        rcases Nat.lt_or_ge j i with h1 | h1
        · exact hz0 j h1
        · rw [show j = i by omega]; exact h0
    · intro _; exact hnz _ (by keeps_tac kk)
  | succ k ih =>
    intro i R hi hz0 kk hc hp
    have hl := hn.lbu (i := i) (by omega)
    have hd := hn.getD_lt i
    bc_run hlive hS [hc, hp, hl] at 0x@B@ 0x@NZ@
    all_goals first | exact acc_heap hS (by omega) (by omega) | skip
    · intro h0
      bsimp [ofNat_eq_zero_iff (show o.ds.getD i 0 < 2 ^ 64 by omega)] at h0
      bc_run hlive hS [hc, hp] at 0x@Z@ 0x@L@
      · intro hc'
        exact absurd ((ofNat_eq_zero_iff (by omega)).mp hc') (by omega)
      · intro _
        refine ih (i + 1) _ (by omega) (fun j hj => ?_) (by keeps_tac kk)
          (by bsimp [show k + 1 + 1 - 1 = k + 1 by omega]) (by bsimp [Nat.add_assoc])
        rcases Nat.lt_or_ge j i with h1 | h1
        · exact hz0 j h1
        · rw [show j = i by omega]; exact h0
    · intro _; exact hnz _ (by keeps_tac kk)

"""

ENTRY = """/-- **The `bc_is_zero` test at `0x@E@`** of the handle in `x@obj@`: `_zero_`
(`x@zr@`) or a number with all digits zero reaches `0x@Z@`, any other number
`0x@NZ@`. -/
theorem kzero_@E@ {live : Nat → Prop} {S : Nat → Prop}
    {Q : (Nat → BitVec 64) → (Nat → BitVec 8) → Prop} (hlive : ∀ p ∈ dcText, live p.1)
    {M : Mem} {R : Nat → BitVec 64} {z : NumObj} {h : Hd} (hS : HeapOwn S)
    (hob : R @obj@ = BitVec.ofNat 64 (Hd.p z h)) (hzr : R @zr@ = BitVec.ofNat 64 z.rep.p)
    (hzb : z.rep.p < 2 ^ 64) (hx : ∀ x, h = some x → NumAt M x.rep ∧ x.rep.p ≠ z.rep.p)
    (hz : ∀ R', Keeps @K@ R' R → HdZero h → DW live S Q 0x@Z@#64 R' M)
    (hnz : ∀ x, h = some x → ∀ R', Keeps @K@ R' R@NZX@ → DW live S Q 0x@NZ@#64 R' M) :
    DW live S Q 0x@E@#64 R M := by
  have htx : tohostAddr = 0x8001ad00 := rfl
  cases h with
  | none =>
    simp only [Hd.p] at hob
    bc_run hlive (fun _ _ _ => hS _ (by assumption) (by assumption)) [hob, hzr] at 0x@Z@
    exact hz _ (by keeps_tac Keeps.refl _ _) fun x hx => nomatch hx
  | some x =>
    obtain ⟨hn, hne⟩ := hx x rfl
    simp only [Hd.p] at hob
    num_facts hn
    have hne' : ¬ BitVec.ofNat 64 x.rep.p = BitVec.ofNat 64 z.rep.p := fun e =>
      hne ((ofNat_eq_iff (by omega) hzb).mp e)
    have hl := hn.len; have hsc := hn.scale; have hv := hn.value
    bc_run hlive hS [hob, hzr, hne', hl, hsc, hv, addw_ofNat] at 0x@L@
    all_goals first | exact acc_heap hS (by omega) (by omega) | skip
    bc_run hlive hS [hob, hzr, hne', hl, hsc, hv, addw_ofNat] at 0x@L@
    all_goals first | exact acc_heap hS (by omega) (by omega) | skip
    · intro hc; exact absurd hc (not_blez (by omega) (by omega))
    intro _
    bc_run hlive hS [hob, hzr, hne', hl, hsc, hv, addw_ofNat] at 0x@L@
    all_goals first | exact acc_heap hS (by omega) (by omega) | skip
    refine kscan_@L@ hlive hS hn ?_ ?_ (x.rep.len + x.rep.scale - 1) 0 _ (by omega)
      (fun j hj => absurd hj (Nat.not_lt_zero _)) (Keeps.refl _ _) ?_ ?_
    · intro R' kk hd
      exact hz R' ((kk.mono (by decide)).trans (by keeps_tac Keeps.refl _ _)) fun y hy => by cases hy; exact hd
    · intro R' kk
      exact hnz x rfl R' ((kk.mono (by decide)).trans (by keeps_tac Keeps.refl _ _))@NZP@
    · bsimp [show x.rep.scale + x.rep.len = x.rep.len + x.rep.scale - 1 + 1 by omega]
    · bsimp []

"""


def hx(n):
    return f"{n:08x}"


def gen():
    out = [HEAD]
    for (e, pair, obj, zr, c, p, t, lr, L, Z) in SITES:
        ks = sorted({c, p, t, lr} | ({15} if pair else set()))
        K = "[" + ", ".join(map(str, ks)) + "]"
        KS = "[" + ", ".join(map(str, sorted({c, p, t}))) + "]"
        keep = lr not in (c, p, t)
        nzx = f" →\n      R' {lr} = BitVec.ofNat 64 x.rep.len" if keep else ""
        nzp = f"\n        (by rw [kk.get {lr} (by decide)]; bsimp [])" if keep else ""
        s = LOOP
        for k, v in [("@L@", hx(L)), ("@B@", hx(L - 12)), ("@NZ@", hx(L + 8)), ("@Z@", hx(Z)),
                     ("@KS@", KS), ("@c@", str(c)), ("@p@", str(p))]:
            s = s.replace(k, v)
        out.append(s)
        s = ENTRY
        for k, v in [("@E@", hx(e)), ("@L@", hx(L)), ("@NZ@", hx(L + 8)), ("@Z@", hx(Z)),
                     ("@K@", K), ("@obj@", str(obj)), ("@zr@", str(zr)), ("@NZX@", nzx),
                     ("@NZP@", nzp)]:
            s = s.replace(k, v)
        out.append(s)
    out.append("end Dc.Mach\n")
    return "".join(out)


def main():
    text = gen()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale; run {sys.argv[0]}")
            sys.exit(1)
        return
    OUT.write_text(text)


if __name__ == "__main__":
    main()
